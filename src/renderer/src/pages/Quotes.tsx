interface FrozenItem {
  quoteItemId: number
  productId: number | null
  description: string
  quantity: string
  unitPrice: string
  unitCost: string
  lineTotal: string
}

interface FrozenSnapshot {
  frozenAt: string
  items: FrozenItem[]
  discount: { type: string; value: string }
  tax: { label: string; rate: string; mode: string }
  shipping: string
  businessInfo: Record<string, unknown>
}

function parseSnapshot(json: string): FrozenSnapshot | null {
  try {
    const p = JSON.parse(json || '{}') as Record<string, unknown>
    if (!p || typeof p !== 'object' || !Array.isArray(p['items'])) return null
    return p as unknown as FrozenSnapshot
  } catch {
    return null
  }
}


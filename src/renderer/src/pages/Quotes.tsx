const TAX_MODES = ['exclusive', 'inclusive', 'none'] as const

interface BusinessInfo {
  name: string
  address: string
  email: string
  phone: string
  logoPath: string
}

async function loadBusinessInfo(): Promise<BusinessInfo> {
  const keys: Array<[keyof BusinessInfo, string]> = [
    ['name', 'pricey.business.name'],
    ['address', 'pricey.business.address'],
    ['email', 'pricey.business.email'],
    ['phone', 'pricey.business.phone'],
    ['logoPath', 'pricey.business.logoPath'],
  ]
  const info = { name: '', address: '', email: '', phone: '', logoPath: '' }
  for (const [k, key] of keys) {
    info[k] = (await api.settingsGet(key).catch(() => null)) ?? ''
  }
  return info
}

export default function Quotes() {
  const [selectedId, setSelectedId] = useState<ID | null>(null)
  const [confirmDelete, setConfirmDelete] = useState<Quote | null>(null)
  const [error, setError] = useState<string | null>(null)
  const q = useAsync(() => api.quotesList(), [])
  const quotes = q.data ?? []

  async function newQuote() {
    setError(null)
    try {
      const info = await loadBusinessInfo()
      const terms = (await api.settingsGet('pricey.business.terms').catch(() => null)) ?? ''
      // Reference is auto-generated by the backend (Q-YYYY-####); totals are
      // frozen on every mutation, so the builder always shows real numbers.
      const created = await api.quotesCreate({
        reference: '',
        business_info_json: JSON.stringify(info),
        terms,
        quote_date: new Date().toISOString().slice(0, 10),
      })
      q.reload()
      setSelectedId(created.id)
    } catch (e) {
      setError(errMsg(e))
    }
  }

  if (selectedId !== null) {
    return (
      <div className="page">
        <QuoteBuilder
          quoteId={selectedId}
          onBack={() => {
            setSelectedId(null)
            q.reload()
          }}
        />
      </div>
    )
  }

  return (
    <div className="page">
      <div className="page-head">
        <h1>Quotations</h1>
        <button type="button" onClick={() => void newQuote()}>
          New quote
        </button>
      </div>
      {error ? <ErrorBanner message={error} /> : null}

      {q.loading ? (
        <Loading />
      ) : q.error ? (
        <ErrorBanner message={q.error} onDismiss={q.reload} />
      ) : quotes.length === 0 ? (
        <div className="card">
          <EmptyState
            title="No quotes yet"
            message="Build a quote from your products — totals are frozen on save so later cost changes never rewrite history."
            action={
              <button type="button" onClick={() => void newQuote()}>
                New quote
              </button>
            }
          />
        </div>
      ) : (
        <div className="card">
          <table>
            <thead>
              <tr>
                <th>Reference</th>
                <th>Customer</th>
                <th>Quote date</th>
                <th>Expires</th>
                <th>Total</th>
                <th>Status</th>
                <th></th>
              </tr>
            </thead>
            <tbody>
              {quotes.map((qt) => (
                <tr key={qt.id}>
                  <td>
                    <button type="button" className="link-btn" onClick={() => setSelectedId(qt.id)}>
                      <strong>{qt.reference}</strong>
                    </button>
                  </td>
                  <td>{qt.customer_name || '—'}</td>
                  <td>{fmtDateOnly(qt.quote_date)}</td>
                  <td>{qt.expires_at ? fmtDateOnly(qt.expires_at) : '—'}</td>
                  <td className="money">
                    <Money value={qt.total} />
                  </td>
                  <td>
                    <span className="pill">{qt.status || 'draft'}</span>
                  </td>
                  <td>
                    <div className="row-actions">
                      <button
                        type="button"
                        className="link-btn"
                        onClick={async () => {
                          try {
                            const dup = await api.quotesDuplicate(qt.id)
                            q.reload()
                            setSelectedId(dup.id)
                          } catch (e) {
                            setError(errMsg(e))
                          }
                        }}
                      >
                        Duplicate
                      </button>
                      <button
                        type="button"
                        className="link-btn danger"
                        onClick={() => setConfirmDelete(qt)}
                      >
                        Delete
                      </button>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {confirmDelete ? (
        <ConfirmDialog
          title="Delete quote?"
          message={
            <p>
              Delete quote "{confirmDelete.reference}"? Its frozen snapshot goes with it. This
              cannot be undone.
            </p>
          }
          confirmLabel="Delete"
          danger
          onCancel={() => setConfirmDelete(null)}
          onConfirm={async () => {
            try {
              await api.quotesDelete(confirmDelete.id)
              q.reload()
            } catch (e) {
              setError(errMsg(e))
            }
            setConfirmDelete(null)
          }}
        />
      ) : null}
    </div>
  )
}


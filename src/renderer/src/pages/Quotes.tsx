function QuoteTotalsForm({
  quote,
  onUpdate,
}: {
  quote: Quote
  onUpdate: (patch: Record<string, string>) => void
}) {
  const [discountType, setDiscountType] = useState<DiscountType>(quote.discount_type)
  const [discountValue, setDiscountValue] = useState(
    quote.discount_type === 'pct' ? String(Number(quote.discount_value) * 100) : quote.discount_value,
  )
  const [taxMode, setTaxMode] = useState(quote.tax_mode)
  const [taxRate, setTaxRate] = useState(quote.tax_rate)
  const [taxLabel, setTaxLabel] = useState(quote.tax_label)
  const [shipping, setShipping] = useState(quote.shipping)

  function applyDiscount() {
    if (discountType === 'pct') {
      if (!isDecimalString(discountValue) || new Decimal(discountValue).isNegative() || new Decimal(discountValue).gte(100)) {
        return
      }
      onUpdate({ discount_type: 'pct', discount_value: new Decimal(discountValue).div(100).toString() })
    } else {
      if (discountValue.trim() !== '' && (!isDecimalString(discountValue) || new Decimal(discountValue).isNegative())) return
      onUpdate({ discount_type: discountType, discount_value: discountValue.trim() || '0' })
    }
  }

  function applyTax() {
    if (taxRate.trim() !== '' && (!isDecimalString(taxRate) || new Decimal(taxRate).isNegative())) return
    onUpdate({ tax_mode: taxMode, tax_rate: taxRate.trim() || '0', tax_label: taxLabel })
  }

  return (
    <div className="form-grid">
      <Field label="Discount type">
        <Select
          value={discountType}
          onChange={(v) => setDiscountType(v as DiscountType)}
          options={[
            { value: 'none', label: 'No discount' },
            { value: 'pct', label: '% off subtotal' },
            { value: 'fixed', label: 'Fixed amount off' },
          ]}
        />
      </Field>
      {discountType !== 'none' ? (
        <Field label={discountType === 'pct' ? 'Discount %' : 'Discount amount'}>
          <div className="toolbar" style={{ margin: 0 }}>
            <NumberInput value={discountValue} onChange={setDiscountValue} />
            <button type="button" className="secondary" onClick={applyDiscount}>
              Apply
            </button>
          </div>
        </Field>
      ) : (
        <Field label="Discount">
          <button type="button" className="secondary" onClick={() => onUpdate({ discount_type: 'none', discount_value: '0' })}>
            Clear discount
          </button>
        </Field>
      )}
      <Field label="Tax mode">
        <Select
          value={taxMode}
          onChange={setTaxMode}
          options={TAX_MODES.map((m) => ({ value: m, label: m }))}
        />
      </Field>
      {taxMode !== 'none' ? (
        <>
          <Field label="Tax label">
            <TextInput value={taxLabel} onChange={(e) => setTaxLabel(e.target.value)} />
          </Field>
          <Field label="Tax rate %" hint={taxMode === 'inclusive' ? 'Included in the prices.' : 'Added on top.'}>
            <div className="toolbar" style={{ margin: 0 }}>
              <NumberInput value={taxRate} onChange={setTaxRate} />
              <button type="button" className="secondary" onClick={applyTax}>
                Apply
              </button>
            </div>
          </Field>
        </>
      ) : (
        <Field label="Tax">
          <button type="button" className="secondary" onClick={() => onUpdate({ tax_mode: 'none', tax_rate: '0' })}>
            No tax
          </button>
        </Field>
      )}
      <Field label="Shipping">
        <div className="toolbar" style={{ margin: 0 }}>
          <NumberInput value={shipping} onChange={setShipping} />
          <button
            type="button"
            className="secondary"
            onClick={() => {
              if (shipping.trim() !== '' && (!isDecimalString(shipping) || new Decimal(shipping).isNegative())) return
              onUpdate({ shipping: shipping.trim() || '0' })
            }}
          >
            Apply
          </button>
        </div>
      </Field>
    </div>
  )
}

function QuoteFooterForm({
  quote,
  onUpdate,
}: {
  quote: Quote
  onUpdate: (patch: Record<string, string>) => void
}) {
  const info = parseBusinessInfo(quote.business_info_json)
  const [local, setLocal] = useState(info)
  const [lastServer, setLastServer] = useState(quote.business_info_json)
  if (quote.business_info_json !== lastServer) {
    setLastServer(quote.business_info_json)
    setLocal(parseBusinessInfo(quote.business_info_json))
  }
  const setInfo = (k: keyof typeof local, v: string) => setLocal((l) => ({ ...l, [k]: v }))

  return (
    <>
      <Field label="Terms">
        <TextArea value={quote.terms} onChange={(e) => onUpdate({ terms: e.target.value })} />
      </Field>
      <Field label="Notes">
        <TextArea value={quote.notes} onChange={(e) => onUpdate({ notes: e.target.value })} />
      </Field>
      <div className="section-title" style={{ fontSize: 16 }}>
        Business info (printed on the quote)
      </div>
      <div className="form-grid">
        <Field label="Business name">
          <TextInput value={local.name} onChange={(e) => setInfo('name', e.target.value)} />
        </Field>
        <Field label="Address">
          <TextInput value={local.address} onChange={(e) => setInfo('address', e.target.value)} />
        </Field>
        <Field label="Email">
          <TextInput value={local.email} onChange={(e) => setInfo('email', e.target.value)} />
        </Field>
        <Field label="Phone">
          <TextInput value={local.phone} onChange={(e) => setInfo('phone', e.target.value)} />
        </Field>
      </div>
      <div className="toolbar mt-16">
        <button
          type="button"
          className="secondary"
          onClick={() => onUpdate({ business_info_json: JSON.stringify(local) })}
        >
          Save business info
        </button>
      </div>
    </>
  )
}

function parseBusinessInfo(json: string): { name: string; address: string; email: string; phone: string } {
  try {
    const p = JSON.parse(json || '{}') as Record<string, unknown>
    return {
      name: String(p['name'] ?? ''),
      address: String(p['address'] ?? ''),
      email: String(p['email'] ?? ''),
      phone: String(p['phone'] ?? ''),
    }
  } catch {
    return { name: '', address: '', email: '', phone: '' }
  }
}

function QuoteItems({
  quoteId,
  items,
  products,
  onChanged,
  onError,
}: {
  quoteId: ID
  items: QuoteItem[]
  products: Product[]
  onChanged: () => void
  onError: (msg: string) => void
}) {
  const [productId, setProductId] = useState('')
  const [description, setDescription] = useState('')
  const [quantity, setQuantity] = useState('1')
  const [unitPrice, setUnitPrice] = useState('')
  const [lookingUp, setLookingUp] = useState(false)
  const [editing, setEditing] = useState<QuoteItem | null>(null)

  async function pickProduct(id: string) {
    setProductId(id)
    if (!id) {
      setDescription('')
      setUnitPrice('')
      return
    }
    const p = products.find((x) => String(x.id) === id)
    setDescription(p ? p.name : '')
    setLookingUp(true)
    try {
      // Default unit price: the product's default pricing config when one
      // exists, otherwise its unit cost. Editable before adding.
      const configs = await api.pricingConfigsList(Number(id))
      const def = configs.find((c) => c.is_default === 1) ?? configs[0]
      if (def) {
        const r = (await api.pricingCalculate(def.id)) as unknown as { price: string }
        setUnitPrice(r.price)
      } else {
        const c = (await api.productsComputeCost(Number(id))) as unknown as { totalUnitCost: string }
        setUnitPrice(c.totalUnitCost)
      }
    } catch (e) {
      onError(`Could not price "${p?.name}": ${errMsg(e)}`)
      setUnitPrice('')
    }
    setLookingUp(false)
  }

  async function add() {
    if (!description.trim()) {
      onError('A line description is required.')
      return
    }
    if (!isDecimalString(quantity) || !new Decimal(quantity).gt(0)) {
      onError('Quantity must be greater than zero.')
      return
    }
    if (!isDecimalString(unitPrice) || new Decimal(unitPrice).isNegative()) {
      onError('Unit price must be a number >= 0.')
      return
    }
    onError('')
    try {
      await api.quoteItemsAdd(quoteId, {
        product_id: productId ? Number(productId) : null,
        description: description.trim(),
        quantity: quantity.trim(),
        unit_price: unitPrice.trim(),
      })
      setProductId('')
      setDescription('')
      setQuantity('1')
      setUnitPrice('')
      await onChanged()
    } catch (e) {
      onError(errMsg(e))
    }
  }

  return (
    <div>
      <div className="section-title">Line items</div>
      {items.length === 0 ? (
        <p className="muted">No line items yet — add products below.</p>
      ) : (
        <table>
          <thead>
            <tr>
              <th>Description</th>
              <th>Qty</th>
              <th>Unit price</th>
              <th>Line total</th>
              <th></th>
            </tr>
          </thead>
          <tbody>
            {items.map((it) => (
              <tr key={it.id}>
                <td>{it.description}</td>
                <td>{it.quantity}</td>
                <td className="money">
                  <Money value={it.unit_price} />
                </td>
                <td className="money">
                  <Money value={new Decimal(it.quantity).times(it.unit_price).toString()} />
                </td>
                <td>
                  <div className="row-actions">
                    <button type="button" className="link-btn" onClick={() => setEditing(it)}>
                      Edit
                    </button>
                    <button
                      type="button"
                      className="link-btn danger"
                      onClick={async () => {
                        try {
                          await api.quoteItemsRemove(it.id)
                          await onChanged()
                        } catch (e) {
                          onError(errMsg(e))
                        }
                      }}
                    >
                      Remove
                    </button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}

      <div className="form-grid mt-16">
        <Field label="Product (optional)" hint="Prefills the description and a default unit price.">
          <Select
            value={productId}
            onChange={(v) => void pickProduct(v)}
            options={[
              { value: '', label: 'Custom line…' },
              ...products.map((p) => ({ value: String(p.id), label: p.name })),
            ]}
          />
        </Field>
        <Field label="Description">
          <TextInput value={description} onChange={(e) => setDescription(e.target.value)} />
        </Field>
        <Field label="Quantity">
          <NumberInput value={quantity} onChange={setQuantity} inputMode="numeric" />
        </Field>
        <Field label="Unit price" hint={lookingUp ? 'Looking up price…' : undefined}>
          <NumberInput value={unitPrice} onChange={setUnitPrice} />
        </Field>
      </div>
      <div className="toolbar">
        <button type="button" className="secondary" onClick={() => void add()} disabled={lookingUp}>
          Add line
        </button>
      </div>

      {editing ? (
        <QuoteItemModal
          item={editing}
          onClose={() => setEditing(null)}
          onSaved={async () => {
            setEditing(null)
            await onChanged()
          }}
          onError={onError}
        />
      ) : null}
    </div>
  )
}

function QuoteItemModal({
  item,
  onClose,
  onSaved,
  onError,
}: {
  item: QuoteItem
  onClose: () => void
  onSaved: () => void
  onError: (msg: string) => void
}) {
  const [description, setDescription] = useState(item.description)
  const [quantity, setQuantity] = useState(item.quantity)
  const [unitPrice, setUnitPrice] = useState(item.unit_price)

  async function save() {
    if (!description.trim()) {
      onError('A line description is required.')
      return
    }
    if (!isDecimalString(quantity) || !new Decimal(quantity).gt(0)) {
      onError('Quantity must be greater than zero.')
      return
    }
    if (!isDecimalString(unitPrice) || new Decimal(unitPrice).isNegative()) {
      onError('Unit price must be a number >= 0.')
      return
    }
    try {
      await api.quoteItemsUpdate({
        id: item.id,
        description: description.trim(),
        quantity: quantity.trim(),
        unit_price: unitPrice.trim(),
      })
      onSaved()
    } catch (e) {
      onError(errMsg(e))
    }
  }

  return (
    <Modal
      title="Edit line item"
      onClose={onClose}
      footer={
        <>
          <button type="button" className="secondary" onClick={onClose}>
            Cancel
          </button>
          <button type="button" onClick={() => void save()}>
            Save
          </button>
        </>
      }
    >
      <Field label="Description">
        <TextInput value={description} onChange={(e) => setDescription(e.target.value)} autoFocus />
      </Field>
      <div className="form-grid">
        <Field label="Quantity">
          <NumberInput value={quantity} onChange={setQuantity} inputMode="numeric" />
        </Field>
        <Field label="Unit price">
          <NumberInput value={unitPrice} onChange={setUnitPrice} />
        </Field>
      </div>
    </Modal>
  )
}

